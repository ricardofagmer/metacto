import { HistoryEntry } from './history';
import { ClusterReport, DedupeReport, NeedReport, PrecisionRecall, ScoringReport } from './scorers';

export type EvalRun = {
  date: string;
  provider: string;
  model: string | null;
  goldenVersion: string;
  promptVersions: string[];
  durationMs: number;
  dedupe: DedupeReport;
  scoring: ScoringReport;
  need: NeedReport;
  cluster: ClusterReport;
};

function percent(value: number | null): string {
  return value === null ? 'n/a' : `${(value * 100).toFixed(1)}%`;
}

function passRate(passed: number, total: number): string {
  return `${passed}/${total} (${percent(total === 0 ? null : passed / total)})`;
}

function precisionRecallRow(row: PrecisionRecall): string {
  return `| ${row.threshold.toFixed(2)} | ${percent(row.precision)} | ${percent(row.recall)} | ${row.truePositives} | ${row.falsePositives} | ${row.falseNegatives} |`;
}

function similarityList(similarities: Map<string, number>, ids: string[]): string {
  return ids.length === 0 ? '-' : ids.map((id) => (similarities.get(id) ?? 0).toFixed(2)).join(', ');
}

function count<Item extends { passed: boolean }>(items: Item[]): { passed: number; total: number } {
  return { passed: items.filter((item) => item.passed).length, total: items.length };
}

export function summarizeRun(run: EvalRun): HistoryEntry {
  return {
    date: run.date,
    provider: run.provider,
    model: run.model,
    goldenVersion: run.goldenVersion,
    versions: run.promptVersions,
    dedupePrecision: run.dedupe.atDefault.precision,
    dedupeRecall: run.dedupe.atDefault.recall,
    dedupeCases: count(run.dedupe.cases),
    nearMissViolations: run.dedupe.nearMissViolations,
    separationChecks: run.dedupe.separationChecks,
    scoringBands: count(run.scoring.cases),
    scoringOrderings: count(run.scoring.orderings),
    needScorer: run.need.scorer,
    need: count(run.need.cases),
    clusterTogether: run.cluster.together,
    clusterApart: run.cluster.apart,
  };
}

function historyRow(entry: HistoryEntry): string {
  const dedupeVersion = entry.versions.find((version) => version.includes('dedupe')) ?? '-';
  return [
    entry.date,
    entry.goldenVersion,
    dedupeVersion,
    percent(entry.dedupePrecision),
    percent(entry.dedupeRecall),
    `${entry.dedupeCases.passed}/${entry.dedupeCases.total}`,
    String(entry.nearMissViolations),
    `${entry.separationChecks.passed}/${entry.separationChecks.total}`,
    `${entry.need.passed}/${entry.need.total} (${entry.needScorer})`,
  ].join(' | ');
}

const NEED_SCORER_LABELS: Record<NeedReport['scorer'], string> = {
  'keyword-inclusion': 'keyword inclusion',
  'llm-judge': 'LLM judge (keywords diagnostic only)',
};

// Request text stays out of the report on purpose: only names, scores and counts are written.
export function renderReport(run: EvalRun, history: HistoryEntry[]): string {
  const dedupePassed = run.dedupe.cases.filter((result) => result.passed).length;
  const bandsPassed = run.scoring.cases.filter((result) => result.passed).length;
  const orderingsPassed = run.scoring.orderings.filter((result) => result.passed).length;
  const needPassed = run.need.cases.filter((result) => result.passed).length;
  const providerHistory = history.filter((entry) => entry.provider === run.provider);
  return [
    '# Golden-set eval results',
    '',
    'Generated by `evals/run.ts`; do not edit by hand. Re-run after any prompt, threshold, rule or model change.',
    '',
    `- Date: ${run.date}`,
    `- Provider: ${run.provider}${run.model !== null ? ` (model ${run.model})` : ''}`,
    `- Golden set: ${run.goldenVersion}`,
    `- Versions: ${run.promptVersions.join(', ')}`,
    `- Wall time: ${run.durationMs} ms`,
    '',
    '## Summary',
    '',
    '| Capability | Metric | Result |',
    '|---|---|---|',
    `| findDuplicates | precision at default threshold 0.6 | ${percent(run.dedupe.atDefault.precision)} |`,
    `| findDuplicates | recall at default threshold 0.6 | ${percent(run.dedupe.atDefault.recall)} |`,
    `| findDuplicates | case pass rate | ${passRate(dedupePassed, run.dedupe.cases.length)} |`,
    `| findDuplicates | near-miss pairs wrongly returned | ${run.dedupe.nearMissViolations} |`,
    `| findDuplicates | separation checks (dup >= 0.6, distinct < 0.4) | ${passRate(run.dedupe.separationChecks.passed, run.dedupe.separationChecks.total)} |`,
    `| scorePriority | score inside expected band | ${passRate(bandsPassed, run.scoring.cases.length)} |`,
    `| scorePriority | rank agreement (ordered pairs) | ${passRate(orderingsPassed, run.scoring.orderings.length)} |`,
    `| analyze (need) | ${NEED_SCORER_LABELS[run.need.scorer]} | ${passRate(needPassed, run.need.cases.length)} |`,
    `| cluster | duplicate pairs in same theme | ${passRate(run.cluster.together.passed, run.cluster.together.total)} |`,
    `| cluster | unrelated pairs kept apart | ${passRate(run.cluster.apart.passed, run.cluster.apart.total)} |`,
    '',
    'Similarity is on the caller scale for every provider. The heuristic maps its raw TF-IDF cosine onto it',
    '(raw 0.267 = caller 0.6, see `HEURISTIC_COSINE_AT_DEFAULT_THRESHOLD` and evals/README.md); the',
    'rationale string of each heuristic candidate still shows the raw cosine.',
    '',
    `## History (${run.provider})`,
    '',
    '| Date | Golden | Dedupe version | Precision @0.6 | Recall @0.6 | Cases | Near-miss violations | Separation | Need |',
    '|---|---|---|---|---|---|---|---|---|',
    ...providerHistory.map((entry) => `| ${historyRow(entry)} |`),
    '',
    '## Dedupe threshold sweep',
    '',
    '| Threshold | Precision | Recall | TP | FP | FN |',
    '|---|---|---|---|---|---|',
    ...run.dedupe.sweep.map(precisionRecallRow),
    '',
    '## Dedupe cases',
    '',
    '| Case | Pass | Expected-duplicate similarity | Must-not-match similarity |',
    '|---|---|---|---|',
    ...run.dedupe.cases.map(
      (result) => `| ${result.name} | ${result.passed ? 'yes' : 'no'} | ${similarityList(result.similarities, result.expected)} | ${similarityList(result.similarities, result.mustNotMatch)} |`,
    ),
    '',
    '## Scoring cases',
    '',
    '| Case | Score | Expected band | Pass |',
    '|---|---|---|---|',
    ...run.scoring.cases.map((result) => `| ${result.name} | ${result.score} | ${result.band[0]}..${result.band[1]} | ${result.passed ? 'yes' : 'no'} |`),
    '',
    '| Must rank higher | Than | Pass |',
    '|---|---|---|',
    ...run.scoring.orderings.map((result) => `| ${result.higher} | ${result.lower} | ${result.passed ? 'yes' : 'no'} |`),
    '',
    '## Need extraction cases',
    '',
    '| Case | Pass | Missing keywords |',
    '|---|---|---|',
    ...run.need.cases.map((result) => `| ${result.name} | ${result.passed ? 'yes' : 'no'} | ${result.missing.length > 0 ? result.missing.join(', ') : '-'} |`),
    '',
    `Clustering produced ${run.cluster.themeCount} theme(s) over the golden corpus.`,
    '',
  ].join('\n');
}
